        /// מחזיר את שם פרשת השבוע עבור התאריך הנתון, או null אם התאריך מחוץ לטווח
        /// המכוסה בטבלה המאומתת.
        /// </summary>
        public static string? GetParashaName(DateTime gregorianDate)
        {
            DateTime date = gregorianDate.Date;

            if (date < CoverageStart || date > CoverageEnd)
            {
                return null;
            }

            // מוצאים את השבת של השבוע הנוכחי (השבוע מוגדר ראשון עד שבת)
            int daysUntilSaturday = (int)DayOfWeek.Saturday - (int)date.DayOfWeek;
            DateTime saturday = date.AddDays(daysUntilSaturday);

            foreach (var (month, day, name) in Table2026)
            {
                if (saturday.Year == 2026 && saturday.Month == month && saturday.Day == day)
                {
                    return name;
                }
            }

            return null;
        }
